import assert from'node:assert/strict';
import{readFile}from'node:fs/promises';
import{createRequire}from'node:module';
import{fileURLToPath,pathToFileURL}from'node:url';
import path from'node:path';
const root=fileURLToPath(new URL('../',import.meta.url)),require=createRequire(path.join(root,'web/package.json'));
const file=path.join(root,'scratch/construction-audio-test.mjs');
await require('esbuild').build({stdin:{contents:"export{Game}from'./src/engine/game.ts';export{G,STRUCTURE,SELECTION}from'./src/engine/core.ts';export{DuneRom}from'./src/rom/dune.ts';",resolveDir:path.join(root,'web')},bundle:true,platform:'node',format:'esm',outfile:file});
const{Game,G,STRUCTURE,SELECTION,DuneRom}=await import(pathToFileURL(file));
const bytes=new Uint8Array(await readFile(path.join(root,'rom/dune_usa.gen'))),game=new Game(new DuneRom(bytes));
game.load('A',1);game.player.credits=10000;
const cy=G.structureFind.find(s=>s.o.type===STRUCTURE.CONSTRUCTION_YARD&&s.o.houseID===G.playerHouseID);
assert.ok(cy);
const events=[];
G.onConstructionStart=()=>events.push('order');G.onConstructionComplete=()=>events.push('ready');
G.onSound=id=>events.push(id);G.onFeedback=id=>events.push('feedback:'+id);
game.build(cy,STRUCTURE.WINDTRAP);assert.ok(game.production(cy));assert.equal(events.filter(x=>x==='order').length,1);
cy.countDown=256;
for(let i=0;i<1000&&!game.production(cy)?.ready;i++)game.tick();
assert.ok(game.production(cy)?.ready);assert.equal(events.filter(x=>x==='ready').length,1);
const before=events.length;
assert.equal(game.placeIt(cy,false),true);assert.equal(G.selectionType,SELECTION.PLACE);
assert.equal(events.length,before,'Automatic placement must not interrupt the READY voice');
game.cancelPlace();assert.equal(game.placeIt(cy),true);assert.equal(events.length,before,'Picking a ready building stays silent');
let packed=0;while(packed<4096&&game.canPlaceAt(packed)===0)packed++;
assert.ok(packed<4096);assert.ok(game.place(packed));assert.equal(events.at(-1),0x14);
assert.equal(events.filter(x=>x==='ready').length,1,'Installing must not repeat completion');
assert.equal(bytes[0x6a95c],65);assert.equal(bytes[0x6a87e+0x14],70);assert.equal(bytes[0x6a87e+0x0d],82);
console.log('PASS: order, READY and installation remain distinct; picking a ghost stays silent; successful installation uses menu Installation (GEMS 70).');
