import { createRequire } from "module";
const require = createRequire("/opt/node-tools/node_modules/");
const { chromium } = require("playwright");
const OUT = process.env.OUT ?? "/tmp";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
await page.goto("http://localhost:4173/?debug");
await page.setInputFiles("#rom-file", process.argv[2]);
await page.waitForSelector("canvas.view", { timeout: 20000 });
await page.waitForTimeout(800);
const key = async (k) => { await page.keyboard.press(k); await page.waitForTimeout(120); };
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` });
const st = () => page.evaluate(() => ({ selType: window.dune.G.selectionType, credits: window.dune.world.houses.get(window.dune.world.player).credits, ready: window.dune.view.readyStructures.length, placement: !!window.dune.view.placement, structures: window.dune.world.structures.map((s) => s.type).join(",") }));
await key("Digit1"); await key("Digit1");
console.log("menu:", (await page.$eval(".command", (e) => e.innerText.replace(/\n+/g, " | "))).slice(0, 120));
await key("Digit1"); // ветряк
console.log("after order:", await st());
await page.evaluate(() => { for (let k = 0; k < 400; k++) window.dune.world.step(); });
await page.waitForTimeout(300);
console.log("after build:", await st());
await shot("c1_auto_place");
await page.evaluate(() => { window.dune.view.cursorX = 24 * 32 + 16; window.dune.view.cursorY = 37 * 32 + 16; });
await page.waitForTimeout(150);
await shot("c2_valid");
await key("Digit2");
console.log("after B:", await st());
await page.waitForTimeout(150);
await shot("c3_ok");
await page.evaluate(() => { window.dune.view.cursorX = 24 * 32 + 16; window.dune.view.cursorY = 35 * 32 + 16; });
await key("Digit1");
console.log("A on CY:", await st());
await page.evaluate(() => { window.dune.view.cursorX = 24 * 32 + 16; window.dune.view.cursorY = 37 * 32 + 16; });
await page.waitForTimeout(100);
await key("Digit1");
await page.waitForTimeout(800);
console.log("placed:", await st());
await shot("c4_placed");
console.log("errors:", errors);
await browser.close();
