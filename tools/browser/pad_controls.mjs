import { createRequire } from "module";
const require = createRequire("/opt/node-tools/node_modules/");
const { chromium } = require("playwright");
const OUT = process.env.OUT ?? "/tmp";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
await page.goto("http://localhost:4173/?debug");
await page.setInputFiles("#rom-file", process.argv[2]);
await page.waitForSelector("canvas.view", { timeout: 20000 });
await page.waitForTimeout(800);
const key = async (k) => { await page.keyboard.press(k); await page.waitForTimeout(100); };
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` });
const state = () => page.evaluate(() => {
  const { world, view, G } = window.dune;
  const sel = [...view.selectedUnits].map((u) => `${u.type}@${Math.round(u.x)},${Math.round(u.y)}`);
  return { sel, struct: view.selectedStructure?.type ?? null, marked: view.markedUnit?.type ?? null, cursor: view.cursorKind, selType: G.selectionType };
});
const units = await page.evaluate(() => window.dune.world.units.filter((u) => u.house === window.dune.world.player).map((u) => ({ type: u.type, x: Math.round(u.x), y: Math.round(u.y) })));
console.log("own units", units);
const trike = units.find((u) => u.type === 13) ?? units[0];
const setCursor = (x, y) => page.evaluate(([x, y]) => { window.dune.view.cursorX = x; window.dune.view.cursorY = y; }, [x, y]);
await setCursor(trike.x, trike.y);
await key("Digit1");
console.log("A on unit:", await state());
await shot("r1_selected");
await key("Digit1");
console.log("A on same unit:", await state());
await key("Digit1");
console.log("A again:", await state());
await setCursor(trike.x + 96, trike.y + 64);
await page.waitForTimeout(100);
await shot("r2_aim");
await key("Digit1");
console.log("A on ground (order):", await state());
await page.waitForTimeout(2500);
const after = await page.evaluate((t) => { const u = window.dune.world.units.find((u) => u.house === window.dune.world.player && u.type === t.type); return u && { x: Math.round(u.x), y: Math.round(u.y), action: u.ref.actionID }; }, trike);
console.log("trike after order:", after);
await shot("r3_moved");
// B отменяет выбор
await setCursor(after.x, after.y);
await key("Digit1");
await key("Digit2");
console.log("A then B:", await state());
console.log("errors:", errors);
await browser.close();
