// Главное меню и выбор дома: стрелка по пунктам, НОВАЯ ИГРА → дома, вправо → Ордосы, A → миссия O1. Снимки в $OUT.
import { createRequire } from "module";
const require = createRequire("/opt/node-tools/node_modules/");
const { chromium } = require("playwright");
const OUT = process.env.OUT ?? "/tmp";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
await page.goto("http://localhost:4173/?debug&title");
await page.setInputFiles("#rom-file", process.argv[2]);
await page.waitForSelector(".frontend canvas", { timeout: 20000 });
await page.waitForTimeout(300);
const key = async (k, n = 1) => { for (let i = 0; i < n; i++) { await page.keyboard.press(k); await page.waitForTimeout(80); } };
const shot = async (n) => (await page.$(".frontend canvas")).screenshot({ path: `${OUT}/${n}.png` });
await shot("fe1_title");
await key("ArrowDown"); await shot("fe2_options");
await key("ArrowUp");
await key("Digit1");
await page.waitForTimeout(200);
await shot("fe3_house");
await key("ArrowRight");
await page.waitForTimeout(200);
await shot("fe4_ordos");
await key("Digit1");
await page.waitForTimeout(300);
console.log("меню закрыто:", await page.isHidden(".frontend"), "миссия:", await page.inputValue("#mission-select"));
console.log("errors:", errors);
await browser.close();
